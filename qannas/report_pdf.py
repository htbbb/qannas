"""PDF report (optional, needs reportlab).

Produces a clean, shareable PDF of the assessment — summary, severity
breakdown, and per-finding detail. If reportlab is missing, available() is
False and the orchestrator simply skips the PDF.
"""
from __future__ import annotations

from pathlib import Path


def available() -> bool:
    try:
        import reportlab  # noqa: F401
    except Exception:
        return False
    return True


_SEV_COLOR = {"critical": "#b00020", "high": "#d32f2f", "medium": "#ed6c02",
              "low": "#0277bd", "info": "#555555"}
_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def write_pdf(run_dir: Path, bb, kb, chains=None) -> Path | None:
    if not available():
        return None
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import mm
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                    TableStyle)

    confirmed = [f for f in bb.findings if f.status == "confirmed"]
    needs = [f for f in bb.findings if f.status == "needs_human"]
    confirmed.sort(key=lambda x: _ORDER.get(x.severity, 9))

    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Heading1"], textColor=colors.HexColor("#0d47a1"))
    small = ParagraphStyle("small", parent=styles["Normal"], fontSize=9, textColor=colors.HexColor("#555"))
    path = run_dir / "report.pdf"
    doc = SimpleDocTemplate(str(path), pagesize=A4,
                            topMargin=18 * mm, bottomMargin=18 * mm)
    story = [Paragraph("Qannas Security Assessment", h1),
             Paragraph(f"Target(s): {', '.join(bb.targets)}", small),
             Paragraph(f"Endpoints mapped: {len(bb.endpoints)} &nbsp;·&nbsp; "
                       f"Confirmed: {len(confirmed)} &nbsp;·&nbsp; Needs review: {len(needs)}", small),
             Spacer(1, 8 * mm)]

    # summary table
    sev_counts = {}
    for f in confirmed:
        sev_counts[f.severity] = sev_counts.get(f.severity, 0) + 1
    if sev_counts:
        rows = [["Severity", "Count"]] + [[k.upper(), str(v)] for k, v in
                sorted(sev_counts.items(), key=lambda kv: _ORDER.get(kv[0], 9))]
        t = Table(rows, colWidths=[60 * mm, 30 * mm])
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0d47a1")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
            ("FONTSIZE", (0, 0), (-1, -1), 9)]))
        story += [t, Spacer(1, 6 * mm)]

    if chains:
        story.append(Paragraph("Attack Chains", styles["Heading2"]))
        for c in chains:
            story.append(Paragraph(f"<b>[{c.severity.upper()}] {c.title}</b>", styles["Normal"]))
            story.append(Paragraph(c.narrative, small))
            story.append(Spacer(1, 2 * mm))
        story.append(Spacer(1, 4 * mm))

    def block(f, heading):
        pb = kb.get(f.vuln_class) if kb else None
        title = pb.title if pb else f.vuln_class
        c = _SEV_COLOR.get(f.severity, "#555")
        story.append(Paragraph(f'<font color="{c}"><b>[{f.severity.upper()}]</b></font> {title}',
                               styles["Heading3"]))
        story.append(Paragraph(f"Endpoint: {f.endpoint}", small))
        if pb:
            story.append(Paragraph(f"CWE: {pb.cwe} · OWASP: {pb.owasp}", small))
        if f.evidence:
            story.append(Paragraph(f"Evidence: {f.evidence}", small))
        if f.poc:
            story.append(Paragraph(f"PoC: {f.poc}", small))
        if pb and pb.remediation:
            story.append(Paragraph(f"Remediation: {pb.remediation}", small))
        story.append(Spacer(1, 3 * mm))

    from reportlab.lib.styles import getSampleStyleSheet as _g
    story.append(Paragraph("Confirmed Findings", styles["Heading2"]))
    if confirmed:
        for f in confirmed:
            block(f, "confirmed")
    else:
        story.append(Paragraph("None confirmed.", small))

    if needs:
        story.append(Paragraph("Needs Human Review", styles["Heading2"]))
        for f in needs:
            block(f, "needs")

    story.append(Spacer(1, 6 * mm))
    story.append(Paragraph("Generated by Qannas. Authorized testing only.", small))
    doc.build(story)
    return path
