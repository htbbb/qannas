"""Render blackboard findings to JSON + Markdown in the run directory."""
from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

from .blackboard import Blackboard

SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def write_reports(bb: Blackboard) -> dict[str, Path]:
    confirmed = [f for f in bb.findings if f.status == "confirmed"]
    needs_human = [f for f in bb.findings if f.status == "needs_human"]
    rejected = [f for f in bb.findings if f.status == "rejected"]

    json_path = bb.run_dir / "report.json"
    json_path.write_text(json.dumps({
        "summary": {
            "endpoints": len(bb.endpoints),
            "confirmed": len(confirmed),
            "needs_human": len(needs_human),
            "rejected_false_positives": len(rejected),
        },
        "confirmed": [asdict(f) for f in confirmed],
        "needs_human": [asdict(f) for f in needs_human],
    }, indent=2))

    md_path = bb.run_dir / "report.md"
    md_path.write_text(_markdown(bb, confirmed, needs_human, rejected))
    return {"json": json_path, "markdown": md_path}


def _markdown(bb, confirmed, needs_human, rejected) -> str:
    lines = ["# Qannas assessment report", ""]
    lines += [f"- Targets: {', '.join(bb.targets)}",
              f"- Endpoints mapped: {len(bb.endpoints)}",
              f"- **Confirmed findings: {len(confirmed)}**",
              f"- Needs human review: {len(needs_human)}",
              f"- Rejected (false positives filtered): {len(rejected)}", ""]

    if confirmed:
        lines += ["## Confirmed findings", ""]
        for f in sorted(confirmed, key=lambda x: SEV_ORDER.get(x.severity, 9)):
            lines += [f"### [{f.severity.upper()}] {f.vuln_class} — {f.endpoint}",
                      f"- Detail: {f.detail}",
                      f"- Evidence: {f.evidence}",
                      f"- PoC: `{f.poc}`" if f.poc else "", ""]

    if needs_human:
        lines += ["## Needs human review (heuristic / context-dependent)", ""]
        for f in needs_human:
            lines += [f"- **{f.vuln_class}** @ {f.endpoint} — {f.evidence}"]
        lines.append("")

    lines += ["---",
              "_Generated by Qannas. Authorized testing only; every finding above "
              "was produced against a target in the configured scope._"]
    return "\n".join(l for l in lines if l is not None)
